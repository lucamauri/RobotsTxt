namespace MediaWiki\Extension\RobotsTxt\Tests\Unit;

use MediaWiki\Content\Content;
use MediaWiki\Content\TextContent;
use MediaWiki\Content\WikitextContent;
use MediaWiki\Extension\RobotsTxt\DefaultRulesGenerator;
use MediaWiki\Extension\RobotsTxt\RobotsTxtBuilder;
use MediaWiki\Revision\RevisionLookup;
use MediaWiki\Revision\RevisionRecord;
use MediaWiki\Revision\SlotRecord;
use MediaWiki\Title\Title;
use MediaWiki\Title\TitleFactory;
use MediaWikiUnitTestCase;

/**
 * Tests for {@see RobotsTxtBuilder}.
 *
 * The builder decides which text is served as robots.txt:
 *  1. the text of MediaWiki:Robots.txt, normalised, when it has content;
 *  2. otherwise the generated defaults, when they are enabled;
 *  3. otherwise a fixed allow-all file.
 *
 * What is real and what is replaced:
 *  - The page content is a real TextContent (or WikitextContent) object,
 *    because the builder checks "instanceof TextContent" and a mock would
 *    make that check less honest.
 *  - The revision lookup, the title factory, the revision and the rules
 *    generator are mocks. The generator mock returns a fixed marker text, so
 *    a builder test can only fail because of builder logic, never because the
 *    generated defaults changed: those have their own tests.
 *
 * Every test also states whether the generator must be called. That checks
 * the decision order (page first, defaults only as a fallback) and not just
 * the returned text.
 *
 * @group RobotsTxt
 * @covers \MediaWiki\Extension\RobotsTxt\RobotsTxtBuilder
 */
class RobotsTxtBuilderTest extends MediaWikiUnitTestCase {

	/**
	 * What the mock generator returns. A recognisable marker, so a test can
	 * tell "the defaults were served" from any other text.
	 */
	private const GENERATED = "# generated by the mock\nUser-agent: *\nDisallow: /mock\n";

	/**
	 * The complete text served when there is no usable page and the generated
	 * defaults are turned off.
	 */
	private const ALLOW_ALL_FILE =
		"# RobotsTxt extension: no rules defined, everything is allowed.\n"
		. "User-agent: *\n"
		. "Disallow:\n";

	/**
	 * Create a mock generator and state how often the builder may call it.
	 *
	 * @param bool $expectCall True when the builder must call generate()
	 *   exactly once, false when it must never call it.
	 * @return DefaultRulesGenerator
	 */
	private function makeGenerator( bool $expectCall ): DefaultRulesGenerator {
		$generator = $this->createMock( DefaultRulesGenerator::class );
		$generator->expects( $expectCall ? $this->once() : $this->never() )
			->method( 'generate' )
			->willReturn( self::GENERATED );

		return $generator;
	}

	/**
	 * Create a revision whose main slot holds the given content.
	 *
	 * @param Content|null $content The content, or null for the case of a
	 *   revision whose text is hidden from the public by revision deletion
	 *   (MediaWiki then returns null instead of the content).
	 * @return RevisionRecord
	 */
	private function makeRevision( ?Content $content ): RevisionRecord {
		$revision = $this->createMock( RevisionRecord::class );
		$revision->method( 'getContent' )
			->with( SlotRecord::MAIN )
			->willReturn( $content );

		return $revision;
	}

	/**
	 * Create the builder, wired to mocks that serve the given revision.
	 *
	 * The mocks also check, in every test, that the builder asks for the right
	 * page: the title factory must be asked for NS_MEDIAWIKI and "Robots.txt"
	 * exactly once, and the revision lookup must be asked for the title the
	 * factory returned, exactly once.
	 *
	 * @param RevisionRecord|null $revision What the lookup returns, or null
	 *   when the page does not exist.
	 * @param bool $useDefaults Value of $wgRobotsTxtUseDefaults
	 * @param DefaultRulesGenerator $generator The (mock) generator
	 * @return RobotsTxtBuilder
	 */
	private function makeBuilder(
		?RevisionRecord $revision,
		bool $useDefaults,
		DefaultRulesGenerator $generator
	): RobotsTxtBuilder {
		$title = $this->createMock( Title::class );

		$titleFactory = $this->createMock( TitleFactory::class );
		$titleFactory->expects( $this->once() )
			->method( 'makeTitle' )
			->with( NS_MEDIAWIKI, 'Robots.txt' )
			->willReturn( $title );

		$revisionLookup = $this->createMock( RevisionLookup::class );
		$revisionLookup->expects( $this->once() )
			->method( 'getRevisionByTitle' )
			->with( $this->identicalTo( $title ) )
			->willReturn( $revision );

		return new RobotsTxtBuilder( $revisionLookup, $titleFactory, $generator, $useDefaults );
	}

	/**
	 * Create the revision for one of the "no usable page" scenarios.
	 *
	 * @param string $scenario One of the keys of provideUnusablePageScenarios()
	 * @return RevisionRecord|null Null for the scenario with no revision at all
	 */
	private function makeRevisionForScenario( string $scenario ): ?RevisionRecord {
		return match ( $scenario ) {
			'no revision' => null,
			'hidden revision' => $this->makeRevision( null ),
			'whitespace only' => $this->makeRevision( new TextContent( "  \n\t\n" ) ),
			'empty text' => $this->makeRevision( new TextContent( '' ) ),
			// A Content object that is not TextContent, standing in for any
			// other content model (JSON, CSS and so on).
			'not text content' => $this->makeRevision( $this->createMock( Content::class ) ),
		};
	}

	/**
	 * Cases for the normalisation of the page text.
	 *
	 * Each case is [ the text of the page, the text that must be served ].
	 * The builder converts line endings to "\n" and replaces everything at
	 * the end of the text (blank lines, spaces, tabs) by a single newline. It
	 * does not touch the start of the text or the blank lines inside it.
	 *
	 * @return array<string,array{0:string,1:string}>
	 */
	public static function provideNormalisationCases(): array {
		return [
			'unchanged when already clean' => [
				"User-agent: *\nDisallow: /a\n",
				"User-agent: *\nDisallow: /a\n",
			],
			'missing final newline is added' => [
				"User-agent: *\nDisallow: /a",
				"User-agent: *\nDisallow: /a\n",
			],
			'CRLF line endings become LF' => [
				"User-agent: *\r\nDisallow: /a\r\n",
				"User-agent: *\nDisallow: /a\n",
			],
			'lone CR line endings become LF' => [
				"A\rB\r",
				"A\nB\n",
			],
			'trailing blank lines collapse into one newline' => [
				"A\n\n\n\n",
				"A\n",
			],
			'trailing spaces and tabs after the last line are removed' => [
				"Disallow: /a   \n \t\n",
				"Disallow: /a\n",
			],
			'CRLF and trailing blank lines together' => [
				"A\r\n\r\n\r\n",
				"A\n",
			],
			'leading blank lines are kept' => [
				"\n\nA\n",
				"\n\nA\n",
			],
			'blank lines inside the text are kept' => [
				"A\n\nB\n",
				"A\n\nB\n",
			],
			'a page with only comments is served as written' => [
				"# Deliberately no rules here\n",
				"# Deliberately no rules here\n",
			],
		];
	}

	/**
	 * A page with content is served after normalisation, and the generated
	 * defaults are not used at all. Defaults are enabled here on purpose: the
	 * page must win even when they are available.
	 *
	 * @dataProvider provideNormalisationCases
	 * @param string $pageText The text of MediaWiki:Robots.txt
	 * @param string $expected The text that must be served
	 */
	public function testPageContentIsNormalised( string $pageText, string $expected ): void {
		$builder = $this->makeBuilder(
			$this->makeRevision( new TextContent( $pageText ) ),
			true,
			$this->makeGenerator( false )
		);

		$this->assertSame( $expected, $builder->build() );
	}

	/**
	 * The page is served the same way when the generated defaults are
	 * disabled: the setting only matters when there is no usable page.
	 */
	public function testPageContentIsServedWhenDefaultsAreOff(): void {
		$builder = $this->makeBuilder(
			$this->makeRevision( new TextContent( "User-agent: *\nDisallow: /a\n" ) ),
			false,
			$this->makeGenerator( false )
		);

		$this->assertSame( "User-agent: *\nDisallow: /a\n", $builder->build() );
	}

	/**
	 * A page in the default wikitext content model works as well as one in
	 * the plain "text" model. WikitextContent extends TextContent, which is
	 * why the page works before an administrator changes its content model.
	 */
	public function testWikitextPageIsServed(): void {
		$builder = $this->makeBuilder(
			$this->makeRevision( new WikitextContent( "User-agent: *\r\nDisallow: /b\r\n" ) ),
			true,
			$this->makeGenerator( false )
		);

		$this->assertSame( "User-agent: *\nDisallow: /b\n", $builder->build() );
	}

	/**
	 * Scenarios in which the page gives nothing usable to serve.
	 *
	 * In all of them the builder must behave as if the page did not exist.
	 * The key is the scenario name and also the only argument; the revision
	 * is created inside the test, because mocks cannot be built in a static
	 * data provider.
	 *
	 * @return array<string,array{0:string}>
	 */
	public static function provideUnusablePageScenarios(): array {
		return [
			'no revision' => [ 'no revision' ],
			'hidden revision' => [ 'hidden revision' ],
			'whitespace only' => [ 'whitespace only' ],
			'empty text' => [ 'empty text' ],
			'not text content' => [ 'not text content' ],
		];
	}

	/**
	 * With no usable page and the defaults enabled, the generated defaults
	 * are served, as produced by the generator, and the generator is called
	 * exactly once.
	 *
	 * @dataProvider provideUnusablePageScenarios
	 * @param string $scenario Name of the scenario to build
	 */
	public function testUnusablePageFallsBackToDefaults( string $scenario ): void {
		$builder = $this->makeBuilder(
			$this->makeRevisionForScenario( $scenario ),
			true,
			$this->makeGenerator( true )
		);

		$this->assertSame( self::GENERATED, $builder->build() );
	}

	/**
	 * With no usable page and the defaults disabled, the fixed allow-all file
	 * is served and the generator is never called.
	 *
	 * @dataProvider provideUnusablePageScenarios
	 * @param string $scenario Name of the scenario to build
	 */
	public function testUnusablePageWithDefaultsOffServesAllowAll( string $scenario ): void {
		$builder = $this->makeBuilder(
			$this->makeRevisionForScenario( $scenario ),
			false,
			$this->makeGenerator( false )
		);

		$this->assertSame( self::ALLOW_ALL_FILE, $builder->build() );
	}
}
