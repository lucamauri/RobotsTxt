namespace MediaWiki\Extension\RobotsTxt\Tests\Unit;

use MediaWiki\Content\TextContent;
use MediaWiki\Extension\RobotsTxt\DefaultRulesGenerator;
use MediaWiki\Extension\RobotsTxt\RobotsTxtBuilder;
use MediaWiki\Revision\RevisionLookup;
use MediaWiki\Revision\RevisionRecord;
use MediaWiki\Revision\SlotRecord;
use MediaWiki\Title\Title;
use MediaWiki\Title\TitleFactory;
use MediaWikiUnitTestCase;

/**
 * Tests for the part of {@see RobotsTxtBuilder} that uses $wgRobotsTxtCentralRules and
 * $wgRobotsTxtInheritWildcard.
 *
 * The rules of merging themselves are tested in RulesMergerTest, the validation in
 * CentralRulesValidatorTest. Here only the wiring is checked:
 *  - the fast path: with no central rules and no inheritance, the page is served exactly as
 *    before (RobotsTxtBuilderTest keeps checking the old behaviour with the old constructor
 *    arguments, so it is the regression guard);
 *  - the merge path, for each of the three sources (page, generated defaults, allow-all file);
 *  - the comment lines at the top for invalid settings, which never stop the file from being
 *    served;
 *  - the `Sitemap:` lines of the page and of the settings together.
 *
 * The collaborators are mocks, built as in RobotsTxtBuilderTest. The generator mock returns a
 * fixed marker text, so a test fails only because of builder logic.
 *
 * @group RobotsTxt
 * @covers \MediaWiki\Extension\RobotsTxt\RobotsTxtBuilder
 * @uses \MediaWiki\Extension\RobotsTxt\CentralRulesValidator
 * @uses \MediaWiki\Extension\RobotsTxt\RobotsTxtParser
 * @uses \MediaWiki\Extension\RobotsTxt\RulesMerger
 * @uses \MediaWiki\Extension\RobotsTxt\SitemapBlock
 */
class RobotsTxtBuilderCentralRulesTest extends MediaWikiUnitTestCase {

	/**
	 * What the mock generator returns.
	 */
	private const GENERATED = "# generated by the mock\nUser-agent: *\nDisallow: /mock\n";

	/**
	 * The comment the builder writes for an invalid central rules setting that has one problem.
	 */
	private const CENTRAL_NOTE = "# RobotsTxt: invalid \$wgRobotsTxtCentralRules entries ignored: 1\n";

	/**
	 * The same for the inheritance setting.
	 */
	private const INHERIT_NOTE = "# RobotsTxt: invalid \$wgRobotsTxtInheritWildcard entries ignored: 1\n";

	/**
	 * @param bool $expectCall Whether the builder must call generate() exactly once
	 * @return DefaultRulesGenerator
	 */
	private function makeGenerator( bool $expectCall ): DefaultRulesGenerator {
		$generator = $this->createMock( DefaultRulesGenerator::class );
		$generator->expects( $expectCall ? $this->once() : $this->never() )
			->method( 'generate' )
			->willReturn( self::GENERATED );

		return $generator;
	}

	/**
	 * @param string|null $pageText The text of the page, or null when the page does not exist
	 * @return RevisionRecord|null
	 */
	private function makeRevision( ?string $pageText ): ?RevisionRecord {
		if ( $pageText === null ) {
			return null;
		}
		$revision = $this->createMock( RevisionRecord::class );
		$revision->method( 'getContent' )
			->with( SlotRecord::MAIN )
			->willReturn( new TextContent( $pageText ) );

		return $revision;
	}

	/**
	 * @param string|null $pageText
	 * @param bool $useDefaults
	 * @param array $sitemaps
	 * @param mixed $central Raw value of $wgRobotsTxtCentralRules
	 * @param mixed $inherit Raw value of $wgRobotsTxtInheritWildcard
	 * @return RobotsTxtBuilder
	 */
	private function makeBuilder(
		?string $pageText, bool $useDefaults, array $sitemaps, $central, $inherit
	): RobotsTxtBuilder {
		$title = $this->createMock( Title::class );

		$titleFactory = $this->createMock( TitleFactory::class );
		$titleFactory->method( 'makeTitle' )->with( NS_MEDIAWIKI, 'Robots.txt' )->willReturn( $title );

		$revisionLookup = $this->createMock( RevisionLookup::class );
		$revisionLookup->method( 'getRevisionByTitle' )
			->with( $this->identicalTo( $title ) )
			->willReturn( $this->makeRevision( $pageText ) );

		// The generator is used only when there is no usable page and defaults are on.
		$generatorUsed = $pageText === null && $useDefaults;

		return new RobotsTxtBuilder(
			$revisionLookup,
			$titleFactory,
			$this->makeGenerator( $generatorUsed ),
			$useDefaults,
			$sitemaps,
			$central,
			$inherit
		);
	}

	/**
	 * Cases: [ page text or null, defaults on, sitemaps, central setting, inherit setting,
	 * the text expected ].
	 *
	 * @return iterable
	 */
	public static function provideBuild(): iterable {
		// The fast path: no central rules and nobody inherits.
		yield 'fast path: the page is served as before, inner blank lines kept' => [
			"User-agent: *\n\nDisallow: /a\n\n\n",
			true, [], [], false,
			"User-agent: *\n\nDisallow: /a\n",
		];
		yield 'fast path: an empty array and false are the defaults' => [
			"User-agent: *\r\nDisallow: /a\r\n",
			true, [], [], false,
			"User-agent: *\nDisallow: /a\n",
		];
		yield 'fast path: no page and defaults off gives the allow-all file with its comment' => [
			null, false, [], [], false,
			"# RobotsTxt extension: no rules defined, everything is allowed.\n"
				. "User-agent: *\nDisallow:\n",
		];

		// The merge path with a page.
		yield 'central rules are added to the page, central first' => [
			"User-agent: *\nDisallow: /tmp/\n",
			true, [], [ '*' => [ 'Disallow' => [ '/admin/' ] ] ], false,
			"User-agent: *\nDisallow: /admin/\nDisallow: /tmp/\n",
		];
		yield 'central rules for an agent the page does not have' => [
			"User-agent: *\nDisallow: /a\n",
			true, [], [ 'GPTBot' => [ 'Disallow' => [ '/' ], 'Crawl-delay' => 10 ] ], false,
			"User-agent: GPTBot\nDisallow: /\nCrawl-delay: 10\n\nUser-agent: *\nDisallow: /a\n",
		];
		yield 'a page with only comments keeps them after the central groups' => [
			"# nothing here yet\n",
			true, [], [ '*' => [ 'Disallow' => [ '/a' ] ] ], false,
			"User-agent: *\nDisallow: /a\n\n# nothing here yet\n",
		];
		yield 'inheritance alone, with a page' => [
			"User-agent: *\nDisallow: /w/\n\nUser-agent: GPTBot\nDisallow: /g/\n",
			true, [], [], true,
			"User-agent: *\nDisallow: /w/\n\nUser-agent: GPTBot\nDisallow: /w/\nDisallow: /g/\n",
		];
		yield 'inheritance with a list of agents' => [
			"User-agent: *\nDisallow: /w/\n\nUser-agent: GPTBot\nDisallow: /g/\n\n"
				. "User-agent: ClaudeBot\nDisallow: /c/\n",
			true, [], [], [ 'claudebot' ],
			"User-agent: *\nDisallow: /w/\n\nUser-agent: GPTBot\nDisallow: /g/\n\n"
				. "User-agent: ClaudeBot\nDisallow: /w/\nDisallow: /c/\n",
		];

		// The merge path with the other two sources.
		yield 'central rules with the generated defaults' => [
			null, true, [], [ '*' => [ 'Disallow' => [ '/admin/' ] ] ], false,
			"User-agent: *\nDisallow: /admin/\n# generated by the mock\nDisallow: /mock\n",
		];
		yield 'central rules, no page, defaults off: allow-all without its comment' => [
			null, false, [], [ 'GPTBot' => [ 'Disallow' => [ '/' ] ] ], false,
			"User-agent: GPTBot\nDisallow: /\n\nUser-agent: *\nDisallow:\n",
		];
		yield 'a central wildcard rule replaces the empty Disallow of the allow-all file' => [
			null, false, [], [ '*' => [ 'Disallow' => [ '/a' ] ] ], false,
			"User-agent: *\nDisallow: /a\n",
		];

		// Invalid settings: a comment at the top, the file is still served.
		yield 'an invalid central entry is skipped and reported, the valid rules are merged' => [
			"User-agent: *\nDisallow: /p\n",
			true, [], [ '*' => [ 'Disallow' => [ '/a' ] ], 5 => [ 'Disallow' => [ '/x' ] ] ], false,
			self::CENTRAL_NOTE . "User-agent: *\nDisallow: /a\nDisallow: /p\n",
		];
		yield 'a central setting of the wrong type is reported, the page is served as before' => [
			"User-agent: *\n\nDisallow: /p\n",
			true, [], 'junk', false,
			self::CENTRAL_NOTE . "User-agent: *\n\nDisallow: /p\n",
		];
		yield 'an inheritance setting of the wrong type is reported, the page is served as before' => [
			"User-agent: *\n\nDisallow: /p\n",
			true, [], [], 'yes',
			self::INHERIT_NOTE . "User-agent: *\n\nDisallow: /p\n",
		];
		yield 'both reports, the central rules first' => [
			"User-agent: *\nDisallow: /p\n",
			true, [], 'junk', 'yes',
			self::CENTRAL_NOTE . self::INHERIT_NOTE . "User-agent: *\nDisallow: /p\n",
		];
		yield 'an invalid name in the inheritance list is reported, the valid ones inherit' => [
			"User-agent: *\nDisallow: /w/\n\nUser-agent: GPTBot\nDisallow: /g/\n",
			true, [], [], [ 'GPTBot', 'bad name' ],
			self::INHERIT_NOTE
				. "User-agent: *\nDisallow: /w/\n\nUser-agent: GPTBot\nDisallow: /w/\nDisallow: /g/\n",
		];

		// Sitemap lines of the page and of the settings together.
		yield 'a Sitemap line of the page is kept once and the settings add the others' => [
			"User-agent: *\nDisallow: /a\nSitemap: https://x.example/s.xml\n",
			true,
			[ 'https://x.example/s.xml', 'https://y.example/t.xml' ],
			[ '*' => [ 'Disallow' => [ '/c' ] ] ],
			false,
			"User-agent: *\nDisallow: /c\nDisallow: /a\n\nSitemap: https://x.example/s.xml\n"
				. "\nSitemap: https://y.example/t.xml\n",
		];
		yield 'the settings sitemaps follow the merged defaults' => [
			null, true, [ 'https://y.example/t.xml' ], [ '*' => [ 'Disallow' => [ '/a' ] ] ], false,
			"User-agent: *\nDisallow: /a\n# generated by the mock\nDisallow: /mock\n"
				. "\nSitemap: https://y.example/t.xml\n",
		];
	}

	/**
	 * @dataProvider provideBuild
	 * @param string|null $pageText
	 * @param bool $useDefaults
	 * @param array $sitemaps
	 * @param mixed $central
	 * @param mixed $inherit
	 * @param string $expected
	 */
	public function testBuild(
		?string $pageText, bool $useDefaults, array $sitemaps, $central, $inherit, string $expected
	): void {
		$builder = $this->makeBuilder( $pageText, $useDefaults, $sitemaps, $central, $inherit );

		$this->assertSame( $expected, $builder->build() );
	}
}
